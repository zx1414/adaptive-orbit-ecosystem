#!/usr/bin/env node
/* agentsim 单文件打包器 — 内联 css/js 为 frontend/agentsim.html · 零依赖
 *
 * 用法：node frontend/tools/bundle.mjs
 * 产物：frontend/agentsim.html（双击 file:// 即玩，不依赖网络）
 * 确定性：时间戳取自环境变量 SOURCE_DATE_EPOCH（秒），缺省为固定值——
 *         同一源码两次打包产物逐字节一致（与主项目双跑确定性纪律一致）。
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));   // frontend/tools
const fe = path.resolve(here, "..");                          // frontend
const stripBom = (s) => (s.charCodeAt(0) === 0xfeff ? s.slice(1) : s);

// 构建时间戳：优先 SOURCE_DATE_EPOCH，缺省 2026-11-01T00:00:00Z（本轮冻结值）
const epoch = Number(process.env.SOURCE_DATE_EPOCH) || 1798761600;
const stamp = new Date(epoch * 1000).toISOString().replace("T", " ").slice(0, 16);

let html = stripBom(readFileSync(path.join(fe, "index.html"), "utf8"));

html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => {
  const css = stripBom(readFileSync(path.join(fe, href), "utf8"));
  return "<style>\n" + css + "\n</style>";
});

html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  const js = stripBom(readFileSync(path.join(fe, src), "utf8"));
  return "<script>\n" + js + "\n<\/script>";
});

// 注入确定性构建戳（替换 index.html 里的占位注释）
html = html.replace(/<!--BUILD_STAMP-->/, "<!-- agentsim single-file build " + stamp + " UTC · generated by tools/bundle.mjs -->");

const out = path.join(fe, "agentsim.html");
writeFileSync(out, "\uFEFF" + html, "utf8");
const bytes = readFileSync(out);
console.log("bundle written:", out.split(path.sep).join("/"));
console.log("  chars:", html.length, " bytes:", bytes.length, "(" + (bytes.length / 1024 / 1024).toFixed(2) + " MB)");
